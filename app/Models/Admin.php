use Illuminate\Notifications\Notifiable;
use Illuminate\Auth\Notifications\ResetPassword;

class Admin extends Authenticatable
{
    //
    use HasFactory, Notifiable;
    protected $guard = 'admins';
    protected $table = 'admins';
    protected $fillable = [
        'name',
        'email',
        'password',
        'role',
    ];
    protected $hidden = [
        'password',
        'remember_token',
    ];
}
